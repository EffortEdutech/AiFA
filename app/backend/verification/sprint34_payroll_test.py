    cur.execute("select id from public.approval_tasks where subject_type='salary_advance' and subject_id=%s", (adv1_id,))
    adv1_task_id = cur.fetchone()[0]
    as_user(cur, owner)
    cur.execute("select public.decide_approval_task(%s,'approved')", (adv1_task_id,))
    conn.commit()

    # ================= B: PayrollRun — the hard auto-approval rule =============
