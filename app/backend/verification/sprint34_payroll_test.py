    as_superuser(cur)
    cur.execute("select status from public.payroll_runs where id=%s", (run_id,))
    ok = cur.fetchone()[0] == "approved"
    all_passed &= ok
    print(f"[{'PASS' if ok else 'FAIL'}] PayrollRun flips to 'approved' once its ApprovalTask is decided")

    # ================= C: e-payslip delivery ===================================
